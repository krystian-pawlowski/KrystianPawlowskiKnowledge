#!/bin/sh
# Installs the personal tier of the Claude Code and Cursor context, from this repo.
#
# Counterpart of SolarsplitKnowledge/scripts/setup-claude-code.sh for the personal tier.
# Idempotent, safe to rerun. Creates symlinks only, never copies: the content stays in
# this repo, single source of truth.
#
# What it does, in order:
#   1. links the dispatcher (rule without `paths`) into ~/.claude/rules/, loaded every session
#   2. links every path-scoped rule of this repo (frontmatter with `paths:`) into ~/.claude/rules/
#   3. runs the shared sync script, which discovers claude/skills-manifest.json of this repo
#      because both repos share a parent folder, and generates claude/skills/<name>/SKILL.md
#      and the relative rule.md link
#   4. links every skill of this repo into ~/.claude/skills/
#   5. links every .mdc of this repo into the Cursor workspace root .cursor/rules/, if present
#   6. verifies that every link in ~/.claude/rules/ resolves to a real .md, checks the
#      frontmatter of this repo's rules, and prints the size of the permanent layer
#
# Agent-requestable rules (alwaysApply: false, no `paths`) are deliberately NOT linked into
# ~/.claude/rules/: there, a rule without `paths` loads unconditionally. They reach Claude
# Code as skills only.
#
# Usage: sh scripts/setup-claude-code-personal.sh [cursor-workspace-root]
#   cursor-workspace-root defaults to the grandparent of this repo, which is where the
#   .cursor/rules/ of the workspace lives on this machine.

set -e

REPO="$(cd "$(dirname "$0")/.." && pwd -P)"
GH="$(dirname "$REPO")"
SHARED="$GH/SolarsplitKnowledge"
CL="$HOME/.claude"
WS="${1:-$(dirname "$GH")}"
DISPATCHER="personal-dispatcher"

[ -f "$REPO/.cursor/rules/$DISPATCHER.md" ] || { echo "dispatcher not found: $REPO/.cursor/rules/$DISPATCHER.md"; exit 1; }

mkdir -p "$CL/rules" "$CL/skills"
ko=0

echo "Permanent layer, loaded every session"
ln -sfn "$REPO/.cursor/rules/$DISPATCHER.md" "$CL/rules/$DISPATCHER.md"
echo "  $DISPATCHER"

echo "Path-scoped rules, loaded on matching files"
n=0
for f in "$REPO"/.cursor/rules/*.md; do
  [ -f "$f" ] || continue
  r=$(basename "$f" .md)
  [ "$r" = "$DISPATCHER" ] && continue
  if head -c 4000 "$f" | grep -q '^paths:'; then
    ln -sfn "$f" "$CL/rules/$r.md"
    echo "  $r"
    n=$((n + 1))
  fi
done
[ "$n" = "0" ] && echo "  (none)"

echo "Skills, generated by the shared sync script, then linked"
if [ -f "$SHARED/scripts/sync-claude-skills.py" ]; then
  if out=$(cd "$SHARED" && python3 scripts/sync-claude-skills.py --write 2>&1); then :; else
    echo "  sync-claude-skills.py reported errors:"; ko=$((ko + 1))
  fi
  printf '%s\n' "$out" | grep -v '^  a jour' | sed 's/^/  /'
else
  echo "  SolarsplitKnowledge not found next to this repo, SKILL.md not regenerated"; ko=$((ko + 1))
fi
for d in "$REPO"/claude/skills/*/; do
  [ -d "$d" ] || continue
  s=$(basename "$d")
  ln -sfn "${d%/}" "$CL/skills/$s"
  echo "  $s"
done

if [ -d "$WS/.cursor/rules" ]; then
  echo "Cursor workspace root: $WS/.cursor/rules"
  for f in "$REPO"/.cursor/rules/*.mdc; do
    [ -e "$f" ] || continue
    ln -sfn "$f" "$WS/.cursor/rules/$(basename "$f")"
    echo "  $(basename "$f")"
  done
else
  echo "No .cursor/rules in $WS, Cursor links skipped. Pass the workspace root as argument."
fi

echo ""
echo "Verifying link targets in $CL/rules (a non-.md target never loads)"
for f in "$CL"/rules/*.md; do
  [ -e "$f" ] || { echo "  BROKEN $f"; ko=$((ko + 1)); continue; }
  real=$(python3 -c "import os,sys;print(os.path.realpath(sys.argv[1]))" "$f")
  case "$real" in
    *.md) ;;
    *) echo "  NON-.md TARGET, this rule will not load: $(basename "$f") -> $real"; ko=$((ko + 1)) ;;
  esac
done
[ "$ko" = "0" ] && echo "  all targets are real .md files"

echo ""
echo "Frontmatter of this repo's rules (Claude Code rejects invalid YAML silently)"
if command -v ruby >/dev/null 2>&1; then
  for f in "$REPO"/.cursor/rules/*.md; do
    [ -f "$f" ] || continue
    if ruby -ryaml -e '
      t = File.read(ARGV[0], encoding: "utf-8")
      m = t.match(/\A---\n(.*?)\n---\n/m) or abort "no frontmatter"
      y = YAML.safe_load(m[1])
      abort "not a mapping" unless y.is_a?(Hash)
      d = y["description"]
      abort "description missing" unless d.is_a?(String) && !d.strip.empty?
      g = y["globs"]
      abort "globs must be quoted" unless g.nil? || g.is_a?(String) || g.is_a?(Array)
    ' "$f" 2>/tmp/fm_err.$$; then
      echo "  ok      $(basename "$f")"
    else
      echo "  INVALID $(basename "$f"): $(cat /tmp/fm_err.$$)"; ko=$((ko + 1))
    fi
    rm -f /tmp/fm_err.$$
  done
else
  echo "  ruby not found, frontmatter not checked"
fi

echo ""
echo "Permanent layer (cap 50 KB cumulated, see agent-context-mechanics section 8)"
python3 - "$CL" <<'PY'
import io, re, glob, os, sys
cl = sys.argv[1]
perm = [f for f in sorted(glob.glob(os.path.join(cl, 'rules', '*.md')))
        if not re.search(r'^paths:', io.open(f, encoding='utf-8').read()[:4000], re.M)]
total = 0
for f in perm:
    s = os.path.getsize(f); total += s
    print(f"  {os.path.basename(f):<28} {s/1024:5.1f} KB")
md = os.path.join(cl, 'CLAUDE.md')
if os.path.exists(md):
    s = os.path.getsize(md); total += s
    print(f"  {'CLAUDE.md':<28} {s/1024:5.1f} KB")
print(f"  {'total':<28} {total/1024:5.1f} KB")
PY

echo ""
if [ "$ko" = "0" ]; then
  echo "Done. Open a new Claude Code session. In Cursor, reload the window and open a new conversation."
else
  echo "Done with $ko problem(s), see above."
  exit 1
fi
